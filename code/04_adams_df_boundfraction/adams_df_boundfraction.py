def verify():
    print("Verification:")
    # (a) Plummer analytic DF -- primary check against eddington_f_analytic
    # (the method bound_fraction actually uses), plus a printed comparison
    # against eddington_f_legacy, which quantifies why the analytic
    # inversion is used for reported numbers (see
    # docs/feedback-2026-09.md).
    m = plummer_model(rmin=1e-4, rmax=1e3, n=4000)
    psi, _ = relative_potential(m['x'], m['rho'])
    f_true_fn = lambda e: 24.0 * np.sqrt(2.0) / (7.0 * np.pi**3) * e**3.5

    eps_a, f_a = eddington_f_analytic(m, np.zeros_like(m['rho']), 0.0)
    sel_a = (eps_a > 0.1) & (eps_a < 0.9)
    err_a = np.max(np.abs(f_a[sel_a] - f_true_fn(eps_a[sel_a])) / f_true_fn(eps_a[sel_a]))
    print(f"  (a) Plummer Eddington inversion vs analytic: max rel err = {err_a:.2e}  (analytic method)")
    if err_a >= 0.02:
        import scipy
        print(f"      FAILED. numpy {np.__version__}, scipy {scipy.__version__}")
        print("      eps, f_numeric, f_analytic (sample):")
        for e in (0.15, 0.3, 0.5, 0.7, 0.85):
            j = np.argmin(np.abs(eps_a - e))
            print(f"        {eps_a[j]:.3f}  {f_a[j]:.4e}  {f_true_fn(eps_a[j]):.4e}")
        raise AssertionError("Eddington inversion verification failed -- "
                             "please send the above diagnostic output")
    eps_l, f_l = eddington_f_legacy(m['x'], m['rho'], psi, 0.0)
    sel_l = (eps_l > 0.1) & (eps_l < 0.9)
    err_l = np.max(np.abs(f_l[sel_l] - f_true_fn(eps_l[sel_l])) / f_true_fn(eps_l[sel_l]))
    print(f"      (for comparison, eddington_f_legacy on the same check: {err_l:.2e})")

    # (b) no gas -> F = 1
    mk = king_model(6.0)
    F, diag = bound_fraction(mk, np.zeros_like(mk['rho']))
    print(f"  (b) King W0=6, no gas: F_bound = {F:.4f} "
          f"(DF density check err {diag['err']:.1e}, {'OK' if diag['valid'] else 'FAILS ERR_TOL'})")
    assert abs(F - 1.0) < 5e-3

    # (c) identical-profile gas: complete dissolution below SFE = 0.428
    #     (see the module docstring -- conservative by construction)
    for sfe in (0.5, 0.45, 0.4, 1.0 / 3.0):
        rho_g = mk['rho'] * (1.0 - sfe) / sfe
        F, diag = bound_fraction(mk, rho_g)
        flag = '' if sfe > 0.428 else '   <- below the frozen-DF threshold (0.428)'
        bad = '' if diag['valid'] else f"   [reconstruction err {diag['err']:.1e} > ERR_TOL]"
        print(f"  (c) identical profiles, SFE={sfe:.3f}: F_bound = {F:.4f}{flag}{bad}")
    print("      (the frozen-DF estimate dissolves identical-profile clusters "
          "below SFE=0.428,\n       vs ~1/3 in N-body: conservative by "
          "construction -- see module docstring)")


