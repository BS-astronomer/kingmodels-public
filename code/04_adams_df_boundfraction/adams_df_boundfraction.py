def _mc_thresholds_from_csv(path, f_min=None):
    """Monte Carlo critical SFE per W0 from a per-realization CSV written by
    mc_bound_fraction_agama.py (columns: W0, SFE_target, SFE_actual, seed,
    F_bound, n_iter).

    For each W0 the realizations are grouped by SFE and the SURVIVAL FRACTION
    (share with F_bound > f_min) is formed; the threshold is where that crosses
    1/2, linearly interpolated between the bracketing SFE values, with half the
    gap quoted as the error. Survival probability rather than mean F_bound is
    used because near threshold the outcome is bimodal (Sect. 5), so the mean
    is not a meaningful centre.  Returns {W0: (SFE_crit, err)}; {} if absent.
    """
    if f_min is None:
        f_min = F_MIN
    if path is None:
        return {}
    d = np.loadtxt(path, delimiter=',', skiprows=1, ndmin=2)
    out = {}
    for w in np.unique(d[:, 0]):
        sub = d[d[:, 0] == w]
        sfes = np.unique(np.round(sub[:, 2], 6))
        surv = np.array([np.mean(sub[np.round(sub[:, 2], 6) == s, 4] > f_min)
                         for s in sfes])
        cross = None
        for i in range(1, len(sfes)):
            if surv[i - 1] < 0.5 <= surv[i]:
                cross = (sfes[i - 1], sfes[i], surv[i - 1], surv[i])
        if cross is None:
            continue
        s0, s1, p0, p1 = cross
        sc = s0 + (0.5 - p0) * (s1 - s0) / max(p1 - p0, 1e-12)
        out[float(w)] = (float(sc), float(0.5 * (s1 - s0)))
    return out


def _mc_thresholds_precomputed(path):
    """Read thresholds already reduced by mc_thresholds_n1e5.py.

    Columns: W0, SFE_thr, err_lo, err_hi, err_sym, grid_halfwidth, n_seeds.
    The symmetric bootstrap spread is returned as the error, so the value is a
    sampling uncertainty rather than the SFE-grid half-width that
    _mc_thresholds_from_csv can offer. Returns {W0: (SFE_thr, err)}; {} if the
    file is absent.
    """
    if path is None:
        return {}
    d = np.loadtxt(path, delimiter=',', skiprows=1, ndmin=2)
    return {float(r[0]): (float(r[1]), float(r[4])) for r in d}


