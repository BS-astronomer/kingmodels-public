    diag_cols = np.array([[e, float(v)] for e, v in crit_diag])
    np.savetxt(OUTDIR + 'df_threshold_summary.csv',
               np.column_stack([crit_rows, diag_cols]), fmt='%.6f',
               delimiter=', ', header='W0, SFE_crit_DF, worst_err, valid',
               comments='')
    n_bad = int((diag_cols[:, 1] == 0.0).sum())
    if n_bad:
        print(f"\n  ** {n_bad}/{len(crit_diag)} King SFE_crit_DF values in "
              f"df_threshold_summary.csv failed the ERR_TOL={ERR_TOL:.0%} "
              "reconstruction check (valid=0) -- do not quote them without "
              "checking worst_err in that column. **")
    print("\nFigs 10-11 + table done.")


