#!/usr/bin/env python3
"""
adams_df_boundfraction.py
=========================
Bound fraction after instantaneous gas expulsion computed directly from the
stellar distribution function, following the approach of Adams (2000) and
Boily & Kroupa (2003a), applied to our derived (Parmentier & Pfalzner 2013)
gas profiles.

Method
------
1. The isotropic stellar DF f(eps) is obtained by Eddington inversion of
   the stellar density rho_*(r) in the TOTAL (stars + gas) relative
   potential Psi_tot(r) (G = M_* = a = 1; Psi = -Phi, Phi(inf) = 0).
2. At gas expulsion the DF is frozen: every star keeps (r, v).
3. A star is bound iff v^2/2 < Psi_b(r), where Psi_b is the relative
   potential generated by the BOUND stars only. Since removing unbound
   stars shallows the potential and unbinds more stars, the criterion is
   iterated to convergence (positions held fixed; violent relaxation and
   recapture are neglected, cf. Sect. 5 caveats):
       rho_b(r) = 4 pi sqrt(2) int_{eps_min(r)}^{Psi_tot(r)}
                  f(eps) sqrt(Psi_tot - eps) d eps ,
       eps_min(r) = max(Psi_t, Psi_tot(r) - Psi_b(r)),
   where Psi_t = Psi_tot(r_t) for truncated (King) models and 0 otherwise.
4. F_bound = M_b / M_*; the DF-based critical SFE is where F_bound
   drops below F_MIN.

Verification built in:
  (a) pure Plummer inversion reproduces the analytic
      f(eps) = 24 sqrt(2)/(7 pi^3) eps^{7/2};
  (b) SFE = 1 (no gas) returns F_bound = 1;
  (c) identical-profile gas: the iterated criterion dissolves the cluster
      completely below SFE = 0.428 (King W0=6; 0.438 for Plummer).

VALIDATION AGAINST BOILY & KROUPA (2003a, MNRAS 338, 665 = Paper I)
-------------------------------------------------------------------
Their Eq. (7) is the scheme implemented here: the bound fraction at each
radius is the fraction of the local velocity distribution below the escape
speed of the stars alone, iterated by recomputing the potential from the
E <= 0 stars only.  For the Plummer sphere they solve it analytically and
find total dissolution below eps = 0.442201 with lambda_e = 0.509404 there.
Our numerical implementation gives 0.4376 (0.9 per cent low), and reproduces
their published bound-fraction curve (their Paper II, Table 1):

    SFE     0.80   0.70   0.60   0.55   0.50   0.45   0.40
    ours    0.998  0.989  0.955  0.914  0.838  0.645  0.000
    BK03a   0.99   0.99   0.95   0.92   0.85   0.69   0.00
    N-body  0.98   0.95   0.86   0.78   0.66   0.44   0.00

Two consequences worth keeping in mind:
  * the widely quoted "SFE > 1/3 for survival" is an N-BODY result with
    collisional effects (Lada et al. 1984; Geyer & Burkert 2001; Kroupa,
    Aarseth & Hurley 2001).  BK03b state explicitly that strictly
    collisionless evolution would give complete dissolution at eps = 0.33,
    the N-body survival there being due to two-body relaxation deepening
    the core during a finite expulsion time.  Our zeros below ~0.43 are
    therefore the correct collisionless answer, not a failure.
  * BK03b Sect. 4.3 introduce a modified scheme (their Eq. 13) tuned to
    match N-body for King models, by resetting the DF cut-off velocity to
    v_e^2 = 2(phi_star[E<0] + phi_gas).  Two readings of that prescription
    bracket their tabulated values rather than reproducing them, so it is
    NOT implemented here; the paper's DF numbers use the Paper I scheme
    above and are calibrated instead against the Monte Carlo runs of
    Sect. 5.  Paper I Table 1 lists polytrope thresholds for n > 5, but
    those models have infinite mass and extent and are not reproducible on
    a finite grid -- only the n = 5 (Plummer) entry is a valid check. This is EXPECTED and is the known bias of
      the frozen-DF estimate, not a failure:
        * the whole-system energy criterion gives E_tot > 0 for SFE < 0.5
          (identical profiles: T = |W_ss|/(2 SFE)), so the cluster as a whole
          is formally unbound below 0.5;
        * N-body with instantaneous expulsion nevertheless retains a remnant
          down to SFE ~ 1/3, because the escaping stars leave gradually and
          the survivors revirialize -- physics the frozen DF discards;
        * the SINGLE-PASS criterion (bound if v^2/2 < Psi_star, no iteration)
          errs the other way, giving F_b = 0.72 at SFE = 1/3.
      Single-pass and iterated therefore BRACKET the N-body answer
      (0.72 vs 0.00 at SFE = 1/3); this code deliberately uses the
      conservative (iterated) branch, and Sect. 5 of the paper quotes the
      Monte Carlo results, which inherit the same conservatism.
"""

