F_MIN = 0.02          # bound fraction defining the DF-based threshold
# ----------------------------------------------------------------------
# EDDINGTON INVERSION. eddington_f_analytic() constructs d(rho)/dPsi and
# d^2(rho)/dPsi^2 analytically (see its docstring) rather than by chained
# finite differencing, which makes N_EPS a genuinely convergent quadrature
# resolution: raising it shrinks the reconstruction error monotonically
# (King W0=9: 9.8/3.6/1.3/0.46/0.16 per cent at N_EPS=500/1000/2000/4000/8000,
# with F_b stable to <0.02 per cent throughout).
# N_EPS=2000 is the default: typically 1-5 per cent reconstruction error at
# ~3x the per-call cost of N_EPS=1000. Raising it costs runtime linearly, so
# prefer the escalation ladder below over a global increase.
N_EPS = 2000

# bound_fraction() retries at increasing resolution whenever an evaluation
# fails ERR_TOL. Each rung is tried only for evaluations that failed the one
# before it: King W0<=6.5 and all of Plummer never leave the first rung, most
# of the rest resolves at 8000, and 32000 is reserved for the hardest cases
# (King W0>=14, Dehnen gamma=1 and 2, dense-scan W0>=11.5).
N_EPS_LADDER = (2000, 8000, 32000)
assert N_EPS_LADDER[0] == N_EPS, "N_EPS and N_EPS_LADDER[0] must match"

# ----------------------------------------------------------------------
# VALIDATION GATE: bound_fraction() self-checks by
# reconstructing rho_star from the just-inverted f(eps) at psi_cap=inf;
# ERR_TOL is the threshold on that reconstruction's max relative error (over
# the 1-95% mass shell) below which a DF evaluation is trusted. Every DF
# number this module produces ships with the 'err'/'valid' diagnostic that
# triggered it, in the printed tables and in the CSV outputs.
# ----------------------------------------------------------------------
ERR_TOL = 0.01         # max tolerated |rho_check - rho_star| / rho_star, 1-95% mass shell


def relative_potential(x, rho):
    """Psi(r) = G [ M(<r)/r + 4 pi int_r^rmax rho r dr ] on the grid x."""
    M = 4.0 * np.pi * cumulative_trapezoid(rho * x**2, x, initial=0.0)
    outer = 4.0 * np.pi * cumulative_trapezoid((rho * x)[::-1], x[::-1], initial=0.0)[::-1] * (-1.0)
    # note: integrating reversed grid gives negative dx; the (-1) restores sign
    return M / x + outer, M


def eddington_f_legacy(x, rho_s, psi_tot, psi_t, return_diag=False):
    """Finite-difference Eddington inversion. NOT for reported numbers --
    use eddington_f_analytic. Retained for bound_fraction_bk13 and for the
    accuracy comparison printed by verify().

    Inverts rho_*(Psi_tot) for eps in (psi_t, psi0], returning (eps_grid, f)
    with f(eps<=psi_t)=0 by construction. It takes two CHAINED finite-
    difference derivatives of a tabulated density, which is ill-conditioned:
    the second stencil's width is set by the N_EPS spacing, so N_EPS controls
    the estimator's noise/bias trade-off rather than just its sampling
    resolution. For cuspy profiles the reconstruction self-check in
    bound_fraction() can fail by many orders of magnitude as a result.

    f is clipped to max(f, 0) before returning, because bound_fraction()
    needs f>=0. A positivity test applied to the RETURNED f is therefore
    vacuous; pass return_diag=True for the pre-clip diagnostic
    {'neg_frac', 'worst_rel_negativity', 'clipped_any'}, which is what
    df_positivity_check.py inspects."""
    u = psi_tot - psi_t                      # shifted potential, >=0, decreasing in r
    keep = u > 0
    u_k, rho_k = u[keep][::-1], rho_s[keep][::-1]     # ascending in u
    uu, idx = np.unique(u_k, return_index=True)
    rr = rho_k[idx]
    # version-proof derivative + interpolation (avoid spline pathologies
    # observed on some numpy/scipy combinations): centered differences on
    # the nonuniform grid, linear interpolation for evaluation.
    drho_du = np.gradient(rr, uu)
    def dr_interp(u):
        return np.interp(u, uu, drho_du)

    q_grid = np.geomspace(1e-8 * uu[-1], uu[-1], N_EPS)  # q = eps - psi_t (log: resolves halo energies)
    # I(q) = int_0^q (drho/du) du / sqrt(q-u); substitute u = q - t^2
    I = np.empty_like(q_grid)
    for i, q in enumerate(q_grid):
        t = np.linspace(0.0, np.sqrt(q), 200)
        I[i] = 2.0 * np.trapezoid(dr_interp(np.clip(q - t**2, uu[0], uu[-1])), t)
    f_raw = np.gradient(I, q_grid) / (np.sqrt(8.0) * np.pi**2)
    f = np.maximum(f_raw, 0.0)
    if not return_diag:
        return psi_t + q_grid, f
    fmax = float(f.max()) if f.size else np.nan
    diag = {
        'neg_frac': float(np.mean(f_raw < 0.0)),
        'worst_rel_negativity': float(f_raw.min() / fmax) if fmax > 0 else np.nan,
        'clipped_any': bool(np.any(f_raw < 0.0)),
    }
    return psi_t + q_grid, f, diag


def eddington_f_analytic(model, rho_g, psi_t, return_diag=False, n_eps=None):
    """Eddington inversion of rho_star(Psi_tot), built WITHOUT differentiating
    any tabulated array. This is the inversion used for every reported number.

    The regularized Eddington formula needs d(rho)/dPsi and d^2(rho)/dPsi^2,
    not rho(Psi) itself:
        f(eps) = (1/sqrt(8) pi^2) [ int_0^eps (d^2 rho/dPsi^2) dPsi/sqrt(eps-Psi)
                                     + (1/sqrt(eps)) (d rho/dPsi)|_{Psi=0} ]
    Both derivatives are obtained by the CHAIN RULE THROUGH r, using pieces
    that are each already analytic or already-computed (no np.gradient of a
    density array anywhere):
      * rho_star'(r), rho_star''(r): analytic per profile family -- for King,
        rho_hat_prime/rho_hat_dprime(W) times dW/dr, d^2W/dr^2 read off the
        structure ODE's own state/RHS (king_model's rho1/rho2); for Plummer
        and Dehnen, elementary closed-form derivatives (plummer_model/
        dehnen_model's rho1/rho2). Model MUST carry rho1, rho2.
      * Psi_tot'(r) = -M_tot(r)/r^2 and Psi_tot''(r) = -4 pi rho_tot(r) +
        2 M_tot(r)/r^3: exact consequences of Gauss's law given the mass
        integral relative_potential() already computes -- algebra on
        already-known M_tot(r)/rho_tot(r), not a finite difference.
      * d(rho)/dPsi = rho1/Psi', d^2(rho)/dPsi^2 = (rho2 Psi' - rho1 Psi'')/Psi'^3.
    What remains is ONE well-posed numerical integral (a t^2-substitution
    quadrature fed an analytic integrand) -- no second differentiation, so
    N_EPS is a genuine quadrature resolution: raising it shrinks the
    reconstruction self-check error monotonically instead of moving the
    answer. See the N_EPS module comment above for the convergence numbers.

    Validated against the analytic pure-Plummer f(eps)=24 sqrt(2)/(7 pi^3)
    eps^3.5 to a max relative error of 5.8e-6; eddington_f_legacy reaches
    5.4e-4 on the same check. verify() prints both.

    return_diag=True adds the pre-clip diagnostic {'neg_frac',
    'worst_rel_negativity', 'clipped_any'}; f itself is clipped at zero.

    n_eps overrides the module-level N_EPS for this call only (used by
    bound_fraction's N_EPS escalation ladder, see N_EPS_LADDER above)."""
    n_eps = N_EPS if n_eps is None else n_eps
    x, rho_s, rho1, rho2 = model['x'], model['rho'], model['rho1'], model['rho2']
    rho_tot = rho_s + rho_g
    psi_tot, M_tot = relative_potential(x, rho_tot)
    with np.errstate(divide='ignore', invalid='ignore'):
        psi1 = -M_tot / x**2                                    # Psi_tot'(r)
        psi2 = -4.0 * np.pi * rho_tot + 2.0 * M_tot / x**3       # Psi_tot''(r)
        drho_dpsi = rho1 / psi1
        d2rho_dpsi2 = (rho2 * psi1 - rho1 * psi2) / psi1**3
    # psi1 -> 0 at r -> 0 (M_tot ~ r^3 there) makes the two ratios above a
    # literal 0/0 at the innermost grid point or two; those are dropped, not
    # patched -- the interpolation below only needs values on a grid dense
    # enough that a couple of edge points cost nothing.
    u = psi_tot - psi_t                      # shifted potential, >=0, decreasing in r
    keep = (u > 0) & np.isfinite(d2rho_dpsi2) & np.isfinite(drho_dpsi)
    order = np.argsort(u[keep])              # ascending in u
    u_k = u[keep][order]
    d2_k, d1_k = d2rho_dpsi2[keep][order], drho_dpsi[keep][order]
    uu, idx = np.unique(u_k, return_index=True)
    d2u, d1u = d2_k[idx], d1_k[idx]
    def d2_interp(u):
        return np.interp(u, uu, d2u)

    q_grid = np.geomspace(1e-8 * uu[-1], uu[-1], n_eps)  # q = eps - psi_t (log: resolves halo energies)
    # I(q) = int_0^q (d^2 rho/dPsi^2) du/sqrt(q-u); substitute u = q - t^2
    I = np.empty_like(q_grid)
    for i, q in enumerate(q_grid):
        t = np.linspace(0.0, np.sqrt(q), 200)
        I[i] = 2.0 * np.trapezoid(d2_interp(np.clip(q - t**2, uu[0], uu[-1])), t)
    # boundary term (drho/dPsi)|_{Psi=0}: uu[0] is the smallest tabulated
    # shifted potential, i.e. the outer edge of the model (r=r_t for
    # truncated/King, r=rmax for infinite-extent Plummer/Dehnen on their
    # finite numerical grid) -- the practical Psi=0 reference in both cases.
    boundary = d1u[0] / np.sqrt(q_grid)
    f_raw = (I + boundary) / (np.sqrt(8.0) * np.pi**2)
    f = np.maximum(f_raw, 0.0)
    if not return_diag:
        return psi_t + q_grid, f
    fmax = float(f.max()) if f.size else np.nan
    diag = {
        'neg_frac': float(np.mean(f_raw < 0.0)),
        'worst_rel_negativity': float(f_raw.min() / fmax) if fmax > 0 else np.nan,
        'clipped_any': bool(np.any(f_raw < 0.0)),
    }
    return psi_t + q_grid, f, diag


def bound_fraction_bk13(model, rho_g, n_iter=80, tol=1e-6):
    """Boily & Kroupa (2003a) 'improved' scheme, their Eq. (13).

    Difference from the plain iterated criterion: the bound stars are treated
    as a SELF-GRAVITATING group that revirializes on a timescale short
    compared with the escape of the unbound ones. Practically, at each
    iteration the distribution function is re-derived by Eddington inversion
    of the CURRENT bound density in the CURRENT bound potential, instead of
    reusing the frozen initial DF. BK03b found this reproduces their N-body
    bound fractions for concentrated King models, where the plain scheme does
    not (their Fig. 3a).
    """
    x, rho_s = model['x'], model['rho']
    psi_tot, _ = relative_potential(x, rho_s + rho_g)
    psi_star, M_s = relative_potential(x, rho_s)
    psi_t = psi_tot[-1] if np.isfinite(model.get('rt', np.inf)) else 0.0

    rho_b = rho_s.copy()
    F_old = 1.0
    for _ in range(n_iter):
        psi_b, M_b = relative_potential(x, rho_b)
        # DF of the current bound population in its own potential
        eps, f = eddington_f_legacy(x, rho_b, psi_b + psi_tot - psi_star, psi_t)
        psi_eff = psi_b + psi_tot - psi_star      # bound stars + (unchanged) gas
        E = eps[None, :]
        PT = psi_eff[:, None]
        EM = np.maximum(psi_t, psi_eff - psi_b)[:, None]
        w = np.where((E >= EM) & (E <= PT),
                     f[None, :] * np.sqrt(np.maximum(PT - E, 0.0)), 0.0)
        rho_new = 4.0 * np.pi * np.sqrt(2.0) * np.trapezoid(w, eps, axis=1)
        rho_b = np.minimum(np.maximum(rho_new, 0.0), rho_s)
        F = relative_potential(x, rho_b)[1][-1]
        if abs(F - F_old) < tol:
            break
        F_old = F
    return F, np.nan


def _bound_fraction_at(model, rho_g, n_eps, n_iter=60, tol=1e-6):
    """bound_fraction's actual computation at a fixed N_EPS. See
    bound_fraction (below) for the public entry point, which adds automatic
    N_EPS escalation on top of this."""
    x, rho_s = model['x'], model['rho']
    psi_tot, _ = relative_potential(x, rho_s + rho_g)
    psi_star, M_s = relative_potential(x, rho_s)
    psi_t = psi_tot[-1] if np.isfinite(model.get('rt', np.inf)) else 0.0

    eps, f = eddington_f_analytic(model, rho_g, psi_t, n_eps=n_eps)

    # rho from the frozen DF given a cap: rho(r) = 4 pi sqrt2 *
    #   int_{eps_min}^{psi_tot} f sqrt(psi_tot - eps) d eps
    def df_density(psi_cap):
        eps_min = np.maximum(psi_t, psi_tot - psi_cap)
        E = eps[None, :]                       # (1, N_EPS)
        PT = psi_tot[:, None]
        EM = eps_min[:, None]
        w = np.where((E >= EM) & (E <= PT), f[None, :] * np.sqrt(np.maximum(PT - E, 0.0)), 0.0)
        return 4.0 * np.pi * np.sqrt(2.0) * np.trapezoid(w, eps, axis=1)

    # consistency: full cap must reproduce rho_s; the pointwise ratio
    # rho_s/rho_check is then applied as a correction factor to cancel the
    # numerical error of the inversion systematically (essential for the
    # infinite-halo models, where uncorrected outer errors otherwise feed a
    # runaway of spurious bound mass through the iteration).
    rho_check = df_density(np.full_like(x, np.inf))
    sel = (M_s > 0.01) & (M_s < 0.95)
    err = float(np.max(np.abs(rho_check - rho_s)[sel] / np.maximum(rho_s, 1e-12)[sel]))
    corr_raw = np.where(rho_check > 0, rho_s / np.maximum(rho_check, 1e-300), 0.0)
    corr = np.clip(corr_raw, 0.0, 2.0)

    psi_b = psi_star.copy()
    F_old = 1.0
    converged = False
    n_used = 0
    for it in range(n_iter):
        rho_b = np.minimum(df_density(psi_b) * corr, rho_s)  # bound subset <= total
        psi_b, M_b = relative_potential(x, rho_b)
        F = M_b[-1]
        n_used = it + 1
        if abs(F - F_old) < tol:
            converged = True
            break
        F_old = F

    diag = {
        'err': err, 'valid': err <= ERR_TOL, 'n_eps': n_eps,
        'corr_min': float(corr_raw[sel].min()), 'corr_max': float(corr_raw[sel].max()),
        'clipped': bool(np.any((corr_raw[sel] < 0.0) | (corr_raw[sel] > 2.0))),
        'n_iter': n_used, 'converged': converged,
    }
    return F, diag


def bound_fraction(model, rho_g, n_iter=60, tol=1e-6):
    """Iterated escape-criterion bound fraction for a model + gas profile.

    Evaluates at N_EPS_LADDER[0] (the module default); if that fails the
    ERR_TOL reconstruction check, retries at each successive rung
    (8000, then 32000) until one passes or the ladder runs out, keeping
    only the last attempt made. Each rung is tried only for evaluations
    that failed the one before it -- most of the pipeline (King W0<=6.5,
    all of Plummer) never leaves the default, and most of the rest resolves
    by 8000; 32000 is reserved for whatever is still failing after that.

    Returns (F, diag). diag is the validation-gate record (see ERR_TOL above):
      err       max |rho_check - rho_star| / rho_star over the 1-95% mass
                shell -- the reconstruction self-consistency check.
      valid     err <= ERR_TOL. False means this evaluation is NOT trusted
                even after the full ladder; F is still returned (nothing is
                hidden), but callers/CSVs/figures should flag it rather than
                quote it silently.
      n_eps     the N_EPS this result actually used -- so every number can
                be traced back to the resolution that produced it.
      escalated True if N_EPS_LADDER[0] failed and this is a retry at a
                higher rung (whether or not the retry itself passed);
                False means the default sufficed.
      corr_min, corr_max   the raw (pre-clip) correction ratio rho_star/
                rho_check over the same shell -- how far off the inversion
                was before the [0,2] clip papered over it.
      clipped   True if the raw ratio left [0,2] anywhere on the shell, i.e.
                the clip is doing more than rounding error -- the applied
                correction cannot cancel the calibration case.
      n_iter, converged   escape-criterion iteration count actually used and
                whether |F-F_old|<tol was reached before n_iter ran out.
    """
    F, diag = _bound_fraction_at(model, rho_g, N_EPS_LADDER[0], n_iter, tol)
    diag['escalated'] = False
    if diag['valid']:
        return F, diag
    for n_eps in N_EPS_LADDER[1:]:
        prev_err = diag['err']
        F, diag = _bound_fraction_at(model, rho_g, n_eps, n_iter, tol)
        diag['escalated'] = True
        diag['err_at_previous_n_eps'] = prev_err   # this rung's predecessor, not necessarily N_EPS_LADDER[0]
        if diag['valid']:
            break
    return F, diag


def fbound_curve(model, tsf_grid, refine=True, f_min=F_MIN, n_ref=6):
    """F_bound(SFE) sweep; if refine, adds n_ref extra tsf points around the
    F = f_min crossing to reduce interpolation error in the threshold.
    Returns (sfes, Fs, valids) -- valids flags each point's reconstruction
    self-check (see ERR_TOL doc above); unused elsewhere in this module but
    kept in the public interface for the same reason the check exists."""
    tsf = list(tsf_grid)
    sfes, Fs, valids = [], [], []
    for t in tsf:
        res = analyze_generic(model, t)
        F, diag = bound_fraction(model, res['rho_g'])
        sfes.append(res['sfe_total'])
        Fs.append(F)
        valids.append(diag['valid'])
    if refine:
        o = np.argsort(sfes)
        Fv = np.array(Fs)[o]
        ts = np.array(tsf)[o]
        ic = np.where(Fv >= f_min)[0]
        if len(ic) and ic[0] > 0:
            lo, hi = ts[ic[0] - 1], ts[ic[0]]
            for t in np.geomspace(lo, hi, n_ref + 2)[1:-1]:
                res = analyze_generic(model, t)
                F, diag = bound_fraction(model, res['rho_g'])
                sfes.append(res['sfe_total'])
                Fs.append(F)
                valids.append(diag['valid'])
    return np.array(sfes), np.array(Fs), np.array(valids)


def fbound_at_sfe(model, sfe, convention='total', return_diag=False):
    """F_bound at a fixed global SFE: inverts SFE -> t_sf for THIS model
    (cheap, gas-mass integrals only), then evaluates the DF bound fraction.
    This keeps different-W0 models comparable at identical SFE points,
    unlike sweeping a common t_sf grid, which samples each model's F(SFE)
    curve in different places.

    return_diag=True also returns the bound_fraction validation diagnostic
    (err/valid/corr_min/corr_max/clipped/n_iter/converged); default False
    keeps the plain-float return every pre-existing caller relies on."""
    tsf = tsf_for_threshold(model, sfe, convention)
    res = analyze_generic(model, tsf)
    F, diag = bound_fraction(model, res['rho_g'])
    return (F, diag) if return_diag else F


def threshold_by_bisection(model, f_min=F_MIN, sfe_lo=0.003, sfe_hi=0.6,
                           n_scan=7, n_bisect=7, convention='total'):
    """DF-based critical SFE via direct bisection in SFE space.
    Coarse log scan brackets the F = f_min crossing, then bisection
    refines it; ~n_scan + n_bisect expensive evaluations per model.

    Returns (sc, scan, Fs, diag). The root-finding itself is UNCHANGED (same
    last-crossing scan + bisection as before); diag just records how much to
    trust the answer it produced -- diag['worst_err'] is the largest
    reconstruction-check error (see ERR_TOL doc above) among every evaluation
    that actually determined sc (the bracketing scan pair plus every
    bisection midpoint), and diag['valid'] = worst_err <= ERR_TOL. A caller
    that gets valid=False should treat sc as unreliable and say so, not
    discard it silently -- the raw number and its error are both in diag."""
    scan = np.geomspace(sfe_lo, sfe_hi, n_scan)
    evals = [fbound_at_sfe(model, s, convention, return_diag=True) for s in scan]
    Fs = np.array([F for F, _ in evals])
    scan_errs = np.array([d['err'] for _, d in evals])
    any_escalated = any(d['escalated'] for _, d in evals)
    lo = hi = lo_i = hi_i = None
    for i in range(1, n_scan):
        if Fs[i - 1] < f_min <= Fs[i]:
            lo, hi = scan[i - 1], scan[i]
            lo_i, hi_i = i - 1, i
    if lo is None:
        diag = {'worst_err': np.nan, 'valid': False, 'scan_errs': scan_errs,
                'any_escalated': any_escalated}
        return (np.nan, scan, Fs, diag)
    worst_err = max(scan_errs[lo_i], scan_errs[hi_i])
    for _ in range(n_bisect):
        mid = np.sqrt(lo * hi)
        Fm, dm = fbound_at_sfe(model, mid, convention, return_diag=True)
        worst_err = max(worst_err, dm['err'])
        any_escalated = any_escalated or dm['escalated']
        if Fm < f_min:
            lo = mid
        else:
            hi = mid
    diag = {'worst_err': worst_err, 'valid': worst_err <= ERR_TOL,
            'scan_errs': scan_errs, 'any_escalated': any_escalated}
    return (np.sqrt(lo * hi), scan, Fs, diag)


